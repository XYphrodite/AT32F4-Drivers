// Table-based (fast) CRC calculation
uint8_t count_CRC(const uint8_t *data, uint32_t length) {
    uint8_t crc = 0xFF; // Initial value
    for (size_t i = 0; i < length; i++) {
        crc = Crc8Table[data[i] ^ crc];
    }
    return crc;
}

uint8_t count_AppCRC(uint32_t addr, uint32_t length) {
    uint8_t crc = 0xFF; // Initial value
    uint8_t data;
    for (size_t i = 0; i < length; i++) {
        data = *reinterpret_cast<uint8_t*>(addr+i);
        crc = Crc8Table[data ^ crc];
    }
    return crc;
}